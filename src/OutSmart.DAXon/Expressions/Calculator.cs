        internal sealed class AnyPlusAny : Calculator
        {
            public override AtomicValue Compute(AtomicValue a, AtomicValue b, IXPathContext c)
            {
                Calculator calc = GetCalculator(a.GetItemType().PrimitiveType, b.GetItemType().PrimitiveType, PLUS, true);
                if (calc == null)
                {
                    throw new XPathException("Unsuitable types for + operation (" + Types.Type.DisplayTypeName(a) + ", " + Types.Type.DisplayTypeName(b) + ")", "XPTY0004", c);
                }
                else
                {
                    return calc.Compute(a, b, c);
                }
            }

            public override IAtomicType GetResultType(IAtomicType typeA, IAtomicType typeB)
            {
                return BuiltInAtomicType.ANY_ATOMIC;
            }
